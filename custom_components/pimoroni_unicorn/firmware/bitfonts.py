"""Bitmap font renderer and font data for Pimoroni Unicorn displays."""


class BitFont:
    """Bitmap font renderer for PicoGraphics."""

    def __init__(self, graphics):
        """Initialise with a PicoGraphics instance."""
        self.graphics = graphics

    @micropython.native
    def draw_char(self, d, x, y, f):
        """Draw a single character d from font f at (x, y); unknown glyphs are skipped."""
        g = f.get(d)
        if g is None:
            return
        for i in range(g["h"]):
            for j in range(g["w"]):
                if g["data"] & (0b1 << ((i * g["w"]) + j)):
                    self.graphics.pixel(g["w"] - 1 - j + x, g["h"] - 1 - i + y)

    @micropython.native
    def draw_text(self, s, x, y, f, d=1):
        """Draw string s from font f at (x, y); d=1 left-justified, d=0 right-justified."""
        if d == 1:
            for ch in s:
                g = f.get(ch)
                if g is None:
                    continue
                self.draw_char(ch, x, y, f)
                x += g["w"] + g["s"]
        else:
            for i in reversed(range(len(s))):
                g = f.get(s[i])
                if g is None:
                    continue
                x -= g["w"]
                self.draw_char(s[i], x, y, f)
                x -= g["s"]


